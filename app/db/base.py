"""SQLAlchemy engine, session factory, and declarative base.

Three Postgres schemas separate concerns:
  raw      - ingested FastF1 data, never mutated by modeling code
  features - derived tables/views built from raw
  ml       - model metadata, versions, metrics
"""

from collections.abc import Iterator

from sqlalchemy import MetaData, create_engine
from sqlalchemy.orm import DeclarativeBase, Session, sessionmaker

from app.config import get_settings

SCHEMA_RAW = "raw"
SCHEMA_FEATURES = "features"
SCHEMA_ML = "ml"

# Explicit naming convention so Alembic generates stable, predictable
# constraint names instead of relying on Postgres defaults. Without this,
# autogenerated migrations produce unnamed constraints that are painful
# to drop later.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


_settings = get_settings()

engine = create_engine(
    _settings.database_url,
    echo=_settings.sql_echo,
    pool_pre_ping=True,  # survive Postgres restarts without stale-connection errors
    future=True,
)

SessionLocal = sessionmaker(bind=engine, autoflush=False, expire_on_commit=False)


def get_session() -> Iterator[Session]:
    """Yield a session, always closing it. Used directly by CLI/scripts."""
    db = SessionLocal()
    try:
        yield db
    finally:
        db.close()
